#!/usr/bin/env python3
"""Build the fixed, checked-in 90-case AEC eval manifest.

Selects a balanced, deterministic subset of wav/aec_challenge_blind/:
  - farend_singletalk : 30 cases (all 5 static + 25 movement, sorted)
  - doubletalk        : 30 cases (all 4 static + 26 movement, sorted)
  - nearend_singletalk: 30 cases (all static -- this corpus has no
                        near-end-singletalk movement variant at all,
                        upstream or in our download)

Static counts are scarce (5 far-end, 4 doubletalk) so every static case
available is included; movement cases fill the remainder up to 30 each,
taken in sorted-stem order for determinism.

Re-run this script any time the corpus under wav/aec_challenge_blind/
changes and you want to regenerate the manifest -- it will reselect
deterministically from whatever is on disk. The manifest actually
checked in (eval/manifest_90case.json) is the frozen snapshot used for
the 2026-08-03 metric-overhaul run; don't regenerate casually, since
regenerating changes which cases baseline/candidate compare against.

Usage:
    python3 eval/build_manifest_90case.py \
        --dataset-dir wav/aec_challenge_blind \
        --out eval/manifest_90case.json \
        --stems-out eval/manifest_90case_stems.txt
"""
import argparse
import glob
import json
import os


def stems(dataset_dir, scenario):
    d = os.path.join(dataset_dir, scenario)
    mics = sorted(glob.glob(os.path.join(d, '*_mic.wav')))
    return [os.path.basename(m)[:-len('_mic.wav')] for m in mics]


def split_static_movement(stem_list):
    static = sorted(s for s in stem_list if '_with_movement' not in s)
    movement = sorted(s for s in stem_list if '_with_movement' in s)
    return static, movement


def select(dataset_dir, scenario, target=30):
    static, movement = split_static_movement(stems(dataset_dir, scenario))
    n_static = len(static)
    n_movement_needed = max(0, target - n_static)
    sel_static = static[:target]  # only bites if a scenario ever has >target static
    sel_movement = movement[:n_movement_needed]
    return sel_static, sel_movement


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dataset-dir', default='wav/aec_challenge_blind')
    ap.add_argument('--out', default='eval/manifest_90case.json')
    ap.add_argument('--stems-out', default='eval/manifest_90case_stems.txt')
    ap.add_argument('--per-category', type=int, default=30)
    args = ap.parse_args()

    manifest = {}
    for scenario in ('farend_singletalk', 'doubletalk', 'nearend_singletalk'):
        static, movement = select(args.dataset_dir, scenario, args.per_category)
        manifest[scenario] = {'static': static, 'movement': movement}

    os.makedirs(os.path.dirname(args.out) or '.', exist_ok=True)
    with open(args.out, 'w') as f:
        json.dump(manifest, f, indent=2)
        f.write('\n')

    with open(args.stems_out, 'w') as f:
        f.write('# Fixed 90-case AEC eval manifest (flat stem list, one per line)\n')
        f.write('# Generated by eval/build_manifest_90case.py -- do not hand-edit.\n')
        f.write('# Compatible with eval_aec_challenge.py --cases-list.\n')
        for scenario in ('farend_singletalk', 'doubletalk', 'nearend_singletalk'):
            for split in ('static', 'movement'):
                stems_sel = manifest[scenario][split]
                if not stems_sel:
                    continue
                f.write(f'\n# {scenario} / {split} ({len(stems_sel)})\n')
                for s in stems_sel:
                    f.write(s + '\n')

    for scenario, d in manifest.items():
        n_static, n_move = len(d['static']), len(d['movement'])
        print(f"{scenario}: static={n_static} movement={n_move} total={n_static + n_move}")


if __name__ == '__main__':
    main()
