"""Per-case A/B statistics, generated rather than hand-summarised.

This exists because a hand-written summary already hid the thing the abort band
is for. The simple-mu evidence README said "worst Δdeg anywhere is −0.034" while
the same JSON contained case-level Δdeg of −0.349, −0.282, −0.232 and −0.207:
−0.034 was a *bucket mean*, and calling it "anywhere" turned a bucket average
into a claim about every case. Bucket means are close to neutral almost by
construction when a change helps some clips and hurts others, so a report that
only prints means cannot fail in the way that matters.

So every report carries, per bucket and overall:

  * mean, median, p10 and the worst five cases, for Δecho and Δdeg separately;
  * counts of cases below −0.05 and below −0.1 on either metric;
  * the single worst case on each metric, named.

`--md` renders the same numbers as Markdown, and `--summary` folds several runs
(engine x grid) into one cross-configuration table so an outlier that appears in
one configuration cannot be averaged away by the others.

    python3 eval/ab_report.py --base b.json --cand c.json --label "C 16k/256" \\
        --out report_c256.json
    python3 eval/ab_report.py --summary report_*.json --md SUMMARY.md
"""
from __future__ import annotations

import argparse
import json
import statistics as st
import sys

# Anything at or below this is a regression the release rule cares about; the
# second is the "investigate the individual case" threshold.
BAND = -0.05
DEEP = -0.10
METRICS = ("echo", "deg")


def percentile(values, q):
    """Nearest-rank percentile. Deliberately not interpolated: with n=4 or n=5
    buckets an interpolated p10 invents a value between two cases and reads as
    if it were measured."""
    if not values:
        return None
    s = sorted(values)
    k = max(0, min(len(s) - 1, int(round((q / 100.0) * (len(s) - 1)))))
    return s[k]


def analyse(base, cand, label):
    common = sorted(set(base) & set(cand))
    missing_cand = sorted(set(base) - set(cand))
    missing_base = sorted(set(cand) - set(base))

    cases = {}
    for stem in common:
        cases[stem] = {
            "bucket": base[stem].get("bucket", "?"),
            "echo_base": base[stem]["echo"], "echo_cand": cand[stem]["echo"],
            "deg_base": base[stem]["deg"], "deg_cand": cand[stem]["deg"],
            "d_echo": cand[stem]["echo"] - base[stem]["echo"],
            "d_deg": cand[stem]["deg"] - base[stem]["deg"],
        }

    def stats(rows, metric):
        vals = [r[f"d_{metric}"] for r in rows]
        if not vals:
            return None
        worst = sorted(rows, key=lambda r: r[f"d_{metric}"])[:5]
        return {
            "n": len(vals),
            "mean": st.mean(vals),
            "median": st.median(vals),
            "p10": percentile(vals, 10),
            "min": min(vals),
            "max": max(vals),
            "n_below_band": sum(1 for v in vals if v <= BAND),
            "n_below_deep": sum(1 for v in vals if v <= DEEP),
            "worst5": [{"stem": r["stem"], "delta": r[f"d_{metric}"]}
                       for r in worst],
        }

    rows = [dict(stem=s, **v) for s, v in cases.items()]
    buckets = sorted({r["bucket"] for r in rows})
    report = {
        "label": label,
        "n_cases": len(rows),
        "missing_from_candidate": missing_cand,
        "missing_from_baseline": missing_base,
        "band": BAND, "deep": DEEP,
        "overall": {m: stats(rows, m) for m in METRICS},
        "buckets": {b: {m: stats([r for r in rows if r["bucket"] == b], m)
                        for m in METRICS} for b in buckets},
        "cases": {r["stem"]: {k: v for k, v in r.items() if k != "stem"}
                  for r in rows},
    }
    report["flagged"] = sorted(
        [{"stem": r["stem"], "bucket": r["bucket"],
          "d_echo": r["d_echo"], "d_deg": r["d_deg"]}
         for r in rows if r["d_echo"] <= DEEP or r["d_deg"] <= DEEP],
        key=lambda r: min(r["d_echo"], r["d_deg"]))
    return report


def _fmt(v, w=7):
    return " " * w if v is None else f"{v:+{w}.3f}"


def render_md(reports):
    L = []
    A = L.append
    A("# A/B report")
    A("")
    A(f"Generated by `eval/ab_report.py`. Band {BAND:+.2f}, deep-dive "
      f"threshold {DEEP:+.2f}. **Every number below is per-case unless the "
      f"column says `mean`** -- a bucket mean is not a statement about any "
      f"individual case, and reporting one as if it were is how a −0.349 "
      f"case-level Δdeg got summarised as \"worst anywhere −0.034\".")
    A("")

    A("## Worst case per configuration (not the mean)")
    A("")
    A("| configuration | n | worst Δecho | case | worst Δdeg | case |")
    A("|---|---:|---:|---|---:|---|")
    for r in reports:
        we = r["overall"]["echo"]["worst5"][0]
        wd = r["overall"]["deg"]["worst5"][0]
        A(f"| {r['label']} | {r['n_cases']} | {we['delta']:+.3f} | "
          f"`{we['stem'][:22]}` | {wd['delta']:+.3f} | `{wd['stem'][:22]}` |")
    A("")

    A("## Regression counts (per case)")
    A("")
    A(f"| configuration | Δecho ≤ {BAND:+.2f} | Δecho ≤ {DEEP:+.2f} | "
      f"Δdeg ≤ {BAND:+.2f} | Δdeg ≤ {DEEP:+.2f} |")
    A("|---|---:|---:|---:|---:|")
    for r in reports:
        e, d = r["overall"]["echo"], r["overall"]["deg"]
        A(f"| {r['label']} | {e['n_below_band']} | {e['n_below_deep']} | "
          f"{d['n_below_band']} | {d['n_below_deep']} |")
    A("")

    for metric in METRICS:
        A(f"## Δ{metric} by bucket")
        A("")
        A("| configuration | bucket | n | mean | median | p10 | worst | "
          f"≤{BAND:+.2f} | ≤{DEEP:+.2f} |")
        A("|---|---|---:|---:|---:|---:|---:|---:|---:|")
        for r in reports:
            for b, per in sorted(r["buckets"].items()):
                s = per[metric]
                if not s:
                    continue
                A(f"| {r['label']} | {b} | {s['n']} | {_fmt(s['mean'])} | "
                  f"{_fmt(s['median'])} | {_fmt(s['p10'])} | {_fmt(s['min'])} "
                  f"| {s['n_below_band']} | {s['n_below_deep']} |")
        A("")

    A(f"## Every case with Δecho ≤ {DEEP:+.2f} or Δdeg ≤ {DEEP:+.2f}")
    A("")
    flagged = [(r["label"], f) for r in reports for f in r["flagged"]]
    if not flagged:
        A("_None._")
    else:
        A("| configuration | bucket | stem | Δecho | Δdeg |")
        A("|---|---|---|---:|---:|")
        for label, f in sorted(flagged, key=lambda x: min(x[1]["d_echo"],
                                                          x[1]["d_deg"])):
            A(f"| {label} | {f['bucket']} | `{f['stem'][:26]}` | "
              f"{f['d_echo']:+.3f} | {f['d_deg']:+.3f} |")
    A("")
    return "\n".join(line.rstrip() for line in L).rstrip() + "\n"


def load_scores(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)["scores"]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base")
    ap.add_argument("--cand")
    ap.add_argument("--label", default="run")
    ap.add_argument("--summary", nargs="*", default=None,
                    help="fold existing report JSONs into one table")
    ap.add_argument("--out")
    ap.add_argument("--md")
    args = ap.parse_args(argv)

    if args.summary is not None:
        reports = [json.load(open(p, encoding="utf-8")) for p in args.summary]
    else:
        if not (args.base and args.cand):
            ap.error("--base and --cand are required without --summary")
        reports = [analyse(load_scores(args.base), load_scores(args.cand),
                           args.label)]

    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            json.dump(reports[0] if len(reports) == 1 else reports, fh,
                      indent=1, sort_keys=True)
            fh.write("\n")
    if args.md:
        with open(args.md, "w", encoding="utf-8") as fh:
            fh.write(render_md(reports))

    for r in reports:
        e, d = r["overall"]["echo"], r["overall"]["deg"]
        print(f"{r['label']:<16} n={r['n_cases']:<3} "
              f"worst Δecho {e['min']:+.3f} ({e['worst5'][0]['stem'][:22]})  "
              f"worst Δdeg {d['min']:+.3f} ({d['worst5'][0]['stem'][:22]})")
        print(f"{'':<16} cases ≤{BAND:+.2f}: echo {e['n_below_band']}, "
              f"deg {d['n_below_band']}   "
              f"≤{DEEP:+.2f}: echo {e['n_below_deep']}, deg {d['n_below_deep']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
