#!/usr/bin/env bash
#
# docs_smoke.sh -- compile-and-run smoke test for the C sample embedded in ../STATIC_MEMORY.md, so the snippet cannot drift
# from the aec_get_mem_size()/aec_init()/aec_destroy() signatures declared in ../include/aec.h.
#
# STATIC_MEMORY.md wraps the sample in HTML comment markers (<!-- docs-smoke:begin --> ... <!-- docs-smoke:end -->). This
# script extracts what lies between them, strips the ```c fence lines, drops it into a generated main() that supplies the
# helpers the snippet assumes (read_block/write_block), compiles it against the real AEC sources and the audiolib archive,
# and runs it on about 1 second of silence.
#
# Run by `make test-docs-smoke` (CC, CXX, BACKEND and COMMON_DIR come from the Makefile) or by hand: cd c_impl/test && ./docs_smoke.sh   (paths resolve
# from the script's location).
# Exit 0 and "docs_smoke: PASS" mean the sample compiles against the current aec.h and runs to completion.

set -euo pipefail

BACKEND="${BACKEND:-ne10}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
C_IMPL_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
COMMON_DIR="$(cd "${COMMON_DIR:-$C_IMPL_DIR/../../audiolib/common}" && pwd)"
DOC="$C_IMPL_DIR/STATIC_MEMORY.md"

if [ ! -f "$DOC" ]; then
    echo "docs_smoke: FAIL — cannot find $DOC" >&2
    exit 1
fi

WORK="$(mktemp -d "${TMPDIR:-/tmp}/docs_smoke.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

echo "== docs_smoke: extracting '## Top-level usage' sample from $DOC =="

# Keep only the lines strictly between the ```c fence and the closing ``` fence, so what is left is pure C.
awk '/<!-- docs-smoke:begin -->/{flag=1; next} /<!-- docs-smoke:end -->/{flag=0} flag' "$DOC" \
    | awk '/^```c$/{incode=1; next} /^```$/{incode=0; next} incode' \
    > "$WORK/sample.c.inc"

if [ ! -s "$WORK/sample.c.inc" ]; then
    echo "docs_smoke: FAIL — no sample extracted between docs-smoke markers in $DOC" >&2
    echo "            (expected '<!-- docs-smoke:begin -->' / '<!-- docs-smoke:end -->' around a \`\`\`c block)" >&2
    exit 1
fi

echo "== docs_smoke: extracted sample =="
cat "$WORK/sample.c.inc"
echo "== end sample =="

cat > "$WORK/docs_smoke_main.c" <<'HEADER_EOF'
/* Auto-generated by docs_smoke.sh — do not edit by hand.
 * Wraps the STATIC_MEMORY.md "Top-level usage" sample in a runnable main()
 * fed ~1 second of silence, so the doc sample is compiled and executed as
 * part of every review pass instead of just eyeballed. */
#include "aec.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int g_samples_left;

/* Stand-ins for the doc's implied "your own audio I/O" callbacks. */
static int read_block(float* mic, float* ref, int hop) {
    if (g_samples_left <= 0) return 0;
    memset(mic, 0, sizeof(float) * (size_t)hop);
    memset(ref, 0, sizeof(float) * (size_t)hop);
    g_samples_left -= hop;
    return 1;
}

static void write_block(const float* out, int hop) {
    (void)out; (void)hop; /* silence in, silence out -- nothing to check here */
}

int main(void) {
    g_samples_left = 16000;            /* about 1 s of silence at 16 kHz, whatever the hop */

HEADER_EOF

cat "$WORK/sample.c.inc" >> "$WORK/docs_smoke_main.c"

cat >> "$WORK/docs_smoke_main.c" <<'FOOTER_EOF'

    printf("docs_smoke: PASS (hop=%d)\n", hop);
    return 0;
}
FOOTER_EOF

echo "== docs_smoke: building audiolib (BACKEND=$BACKEND) =="
make -C "$COMMON_DIR" BACKEND="$BACKEND" lib

# Resolve the archive path for THIS build: print-lib-path is queried with the same BACKEND= as the `lib` build above, so
# the two cannot point at different configs.
COMMON_LIB_PATH="$(make -s -C "$COMMON_DIR" BACKEND="$BACKEND" print-lib-path)"

echo "== docs_smoke: compiling extracted sample against aec.h + libaudio_common ($BACKEND) =="
# Compile as C, then link with the C++ driver: the NE10 archive carries one C++ TU, and the C++ driver supplies the C++
# runtime without a hardcoded -lc++, like the Makefiles' LINK=$(CXX).
LINK_DRV="${CXX:-c++}"

SOURCES=("$WORK/docs_smoke_main.c")
while IFS= read -r -d '' src; do
    SOURCES+=("$src")
done < <(find "$C_IMPL_DIR/src" -name '*.c' -print0)

OBJ_LIST=()
i=0
for src in "${SOURCES[@]}"; do
    obj="$WORK/docs_smoke_obj_$i.o"
    "${CC:-gcc}" -O2 -ffp-contract=off -fno-math-errno -std=gnu99 \
        -I"$C_IMPL_DIR/include" -I"$C_IMPL_DIR/include/internal" -I"$C_IMPL_DIR/example" -I"$COMMON_DIR/include" -I"$COMMON_DIR" \
        -c "$src" -o "$obj"
    OBJ_LIST+=("$obj")
    i=$((i + 1))
done

"$LINK_DRV" "${OBJ_LIST[@]}" "$COMMON_LIB_PATH" -lm -o "$WORK/docs_smoke_bin"

echo "== docs_smoke: running (BACKEND=$BACKEND) =="
"$WORK/docs_smoke_bin"
